#!/usr/bin/env node
/**
 * Copies data/true-false/*.json into src/data/true-false/ (Metro cannot import
 * from tools/) and regenerates src/data/trueFalseBank.ts.
 *
 *   node sync-true-false-to-app.mjs
 */
import { mkdir, readdir, readFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, 'data', 'true-false');
const outDir = path.resolve(here, '../../src/data/true-false');
const bankFile = path.resolve(here, '../../src/data/trueFalseBank.ts');

async function main() {
  const files = (await readdir(srcDir)).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort();
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const subjects = [];
  for (const file of files) {
    const subjectId = file.replace(/\.json$/, '');
    const raw = await readFile(path.join(srcDir, file), 'utf8');
    JSON.parse(raw); // ensure valid
    await writeFile(path.join(outDir, file), raw, 'utf8');
    subjects.push(subjectId);
  }

  const imports = subjects.map((id) => `import ${toIdent(id)} from './true-false/${id}.json';`).join('\n');
  const entries = subjects.map((id) => `  '${id}': ${toIdent(id)},`).join('\n');

  const source = `/* eslint-disable */
/**
 * AUTO-GENERATED by tools/firestore-seed/sync-true-false-to-app.mjs — do not edit.
 * Quiz (True / False) statements ship inside the app so Firestore free-tier
 * write quota is not spent seeding thousands of content documents.
 */
import type { Question } from '@/types';

${imports}

type Statement = { statement: string; answer: boolean; explanation: string; isActive?: boolean };
type BankFile = { subjectId: string; levels: Record<string, Statement[]> };

const banks: Record<string, BankFile> = {
${entries}
};

export const TRUE_FALSE_OPTIONS = ['True', 'False'] as const;

export function trueFalseQuestionId(subjectId: string, level: number, order: number) {
  return \`\${subjectId}__tf__l\${level}__q\${String(order).padStart(2, '0')}\`;
}

function toQuestion(subjectId: string, level: number, order: number, item: Statement): Question {
  return {
    id: trueFalseQuestionId(subjectId, level, order),
    subjectId,
    level,
    question: item.statement.trim(),
    options: [...TRUE_FALSE_OPTIONS],
    correctAnswer: item.answer ? 'True' : 'False',
    explanation: item.explanation.trim(),
    order,
    isActive: item.isActive !== false,
  };
}

/** All active True/False statements for one subject level (local JSON). */
export function getLocalTrueFalseQuestions(subjectId: string, level: number): Question[] {
  const file = banks[subjectId];
  const list = file?.levels?.[String(level)] ?? [];
  return list
    .map((item, i) => toQuestion(subjectId, level, i + 1, item))
    .filter((q) => q.isActive);
}

/** Re-load statements by id for an unfinished session (local JSON). */
export function getLocalTrueFalseByIds(ids: string[]): Question[] | null {
  if (ids.length === 0) return null;
  const byId = new Map<string, Question>();
  for (const [subjectId, file] of Object.entries(banks)) {
    for (const [levelKey, list] of Object.entries(file.levels ?? {})) {
      const level = Number(levelKey);
      list.forEach((item, i) => {
        const q = toQuestion(subjectId, level, i + 1, item);
        byId.set(q.id, q);
      });
    }
  }
  const ordered = ids.map((id) => byId.get(id));
  if (ordered.some((q) => !q || !q.isActive)) return null;
  return ordered as Question[];
}

export const localTrueFalseSubjectIds = Object.keys(banks);
`;

  await writeFile(bankFile, source, 'utf8');
  console.log(`Synced ${subjects.length} true-false files → src/data/true-false/`);
  console.log(`Wrote ${path.relative(process.cwd(), bankFile)}`);
}

function toIdent(subjectId) {
  return subjectId.replace(/-([a-z])/g, (_, c) => c.toUpperCase()).replace(/[^a-zA-Z0-9_]/g, '_');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
